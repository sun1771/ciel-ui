/**
 * Builds tokens.css from tokens.json.
 *
 *   pnpm --filter @cielui/tokens build    write tokens.css
 *   pnpm --filter @cielui/tokens test     fail if tokens.css is out of date
 *
 * Ported from tripon-ai (app/design-system/sd.config.js). It is plain Node, not
 * Style Dictionary: the tokens use Tokens Studio's $extensions.modes for
 * light/dark and web/mobile, which this script maps to:
 *   modes.light / modes.web  → :root
 *   modes.dark               → [data-theme='dark']   (only values that differ)
 *   modes.mobile             → @media (max-width: 440px)
 *   $type duration           → also 0ms in @media (prefers-reduced-motion: reduce)
 *
 * Additions over the original:
 *   - $extensions.a11y.<mode> = { was, note } records a value changed for WCAG
 *     contrast. `was` is the original value (usually a {reference}), so a
 *     change can be reverted by putting it back. `note` is written as an
 *     "a11y:" comment next to the declaration.
 *   - $description is written as a comment above the declaration.
 *   - --check compares instead of writing (used in CI).
 */
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const TOKENS_FILE = path.join(root, 'tokens.json')
const OUTPUT_FILE = path.join(root, 'tokens.css')
const check = process.argv.includes('--check')

const tokens = JSON.parse(fs.readFileSync(TOKENS_FILE, 'utf8'))

// Flatten the tree into  dotted.path → token  (a token is any node with $value).
function flatten(obj, prefix = []) {
  const out = {}
  for (const [key, value] of Object.entries(obj)) {
    if (key.startsWith('$') || value === null || typeof value !== 'object') continue
    if ('$value' in value) out[[...prefix, key].join('.')] = value
    else Object.assign(out, flatten(value, [...prefix, key]))
  }
  return out
}
const all = flatten(tokens)

// Follow {curly.brace} references to a raw value.
function resolve(v, depth = 0) {
  if (typeof v !== 'string' || !v.startsWith('{')) return v
  if (depth > 20) throw new Error(`Reference chain too deep: ${v}`)
  const token = all[v.slice(1, -1)]
  if (!token) throw new Error(`Unresolved token reference: ${v}`)
  return resolve(token.$value, depth + 1)
}

const FONT_WEIGHTS = {
  regular: '400',
  medium: '500',
  'semi bold': '600',
  semibold: '600',
  bold: '700',
}
const fontWeight = (fw) => FONT_WEIGHTS[String(fw).toLowerCase()] ?? fw
const varName = (p) => '--ds-' + p.replace(/\./g, '-')

function comment(text) {
  const lines = text.trim().split('\n')
  return lines.map((l, i) => `  ${i ? '   ' : '/* '}${l}${i === lines.length - 1 ? ' */' : ''}`)
}
function decl(name, value, a11y) {
  return `  ${name}: ${value};` + (a11y?.note ? ` /* a11y: ${a11y.note} */` : '')
}

const rootLines = []
const darkLines = []
const mobileLines = []
const reducedMotionLines = []

for (const [p, token] of Object.entries(all)) {
  const name = varName(p)
  const { $type: type, $value: value, $description: description } = token
  const modes = token.$extensions?.modes
  const a11y = token.$extensions?.a11y ?? {}
  if (description) rootLines.push(...comment(description))

  if (type === 'typography') {
    rootLines.push(`  ${name}-font-family: ${value.fontFamily};`)
    rootLines.push(`  ${name}-font-weight: ${fontWeight(value.fontWeight)};`)
    rootLines.push(`  ${name}-font-size: ${value.fontSize};`)
    rootLines.push(`  ${name}-line-height: ${value.lineHeight};`)
    if (value.letterSpacing && value.letterSpacing !== '0%') {
      rootLines.push(`  ${name}-letter-spacing: ${value.letterSpacing};`)
    }
  } else if (type === 'shadow') {
    const { offsetX, offsetY, blur, spread, color } = value
    rootLines.push(`  ${name}: ${offsetX} ${offsetY} ${blur} ${spread} ${color};`)
  } else if (type === 'cubicBezier') {
    rootLines.push(`  ${name}: cubic-bezier(${resolve(value).join(', ')});`)
  } else if (type === 'fontWeight') {
    rootLines.push(`  ${name}: ${fontWeight(value)};`)
  } else if (modes?.light !== undefined || modes?.dark !== undefined) {
    const light = resolve(modes.light ?? value)
    const dark = resolve(modes.dark ?? value)
    rootLines.push(decl(name, light, a11y.light))
    if (dark !== light) darkLines.push(decl(name, dark, a11y.dark))
  } else if (modes?.web !== undefined || modes?.mobile !== undefined) {
    const web = modes.web ?? value
    const mobile = modes.mobile ?? value
    rootLines.push(`  ${name}: ${web};`)
    if (mobile !== web) mobileLines.push(`  ${name}: ${mobile};`)
  } else {
    rootLines.push(decl(name, resolve(value), a11y.light))
    if (type === 'duration') reducedMotionLines.push(`  ${name}: 0ms;`)
  }
}

const css =
  [
    '/* Design tokens for @cielui/react.',
    '   GENERATED from tokens.json by scripts/build.mjs. Do not edit this file:',
    '   edit tokens.json and run `pnpm --filter @cielui/tokens build`.',
    '   Values marked "a11y:" were changed for WCAG AA contrast; tokens.json keeps',
    '   the original value of each (see packages/ui/ACCESSIBILITY.md and',
    '   packages/ui/DESIGN-CHANGES.md). */',
    '',
    ':root {',
    ...rootLines,
    '}',
    ...(darkLines.length ? ['', "[data-theme='dark'] {", ...darkLines, '}'] : []),
    ...(mobileLines.length
      ? [
          '',
          '@media (max-width: 440px) {',
          '  :root {',
          ...mobileLines.map((l) => '  ' + l),
          '  }',
          '}',
        ]
      : []),
    ...(reducedMotionLines.length
      ? [
          '',
          '@media (prefers-reduced-motion: reduce) {',
          '  :root {',
          ...reducedMotionLines.map((l) => '  ' + l),
          '  }',
          '}',
        ]
      : []),
  ].join('\n') + '\n'

const rel = path.relative(process.cwd(), OUTPUT_FILE)
if (check) {
  const current = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, 'utf8') : ''
  if (current !== css) {
    console.error(
      `✗ ${rel} is out of date with tokens.json. Run \`pnpm --filter @cielui/tokens build\`.`
    )
    process.exit(1)
  }
  console.log(`✓ ${rel} matches tokens.json`)
} else {
  fs.writeFileSync(OUTPUT_FILE, css)
  console.log(
    `✓ wrote ${rel}: ${rootLines.length} :root, ${darkLines.length} dark, ${mobileLines.length} mobile lines`
  )
}
